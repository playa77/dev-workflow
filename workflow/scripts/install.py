def detect(root: Path) -> dict:
    def exists(*names: str) -> bool:
        return any((root / n).exists() for n in names)

    make = root / "Makefile"
    make_text = make.read_text(encoding="utf-8", errors="ignore") if make.exists() else ""
    targets = set(re.findall(r"^([A-Za-z0-9_.-]+):", make_text, re.M))

    if exists("pyproject.toml", "setup.py", "setup.cfg", "pytest.ini", "tox.ini"):
        stack = "python"
        has_pytest = subprocess.run(
            [sys.executable, "-c", "import pytest"], capture_output=True
        ).returncode == 0
        has_tests = (root / "tests").is_dir()
        uses_unittest = False
        if has_tests:
            for path in (root / "tests").rglob("*.py"):
                try:
                    text = path.read_text(encoding="utf-8", errors="ignore")
                except OSError:
                    continue
                if "unittest" in text or "TestCase" in text:
                    uses_unittest = True
                    break
        if has_pytest:
            test_full = "python3 -m pytest -q"
            test_affected = "python3 -m pytest -q -m 'not slow'"
            test_smoke = "python3 -m pytest -q -m smoke"
        elif has_tests and uses_unittest:
            # unittest discovery only collects TestCase classes. Without an
            # __init__.py in tests/, `-t .` fails because the directory is not
            # importable as a package.
            package = (root / "tests" / "__init__.py").exists()
            test_full = ("python3 -m unittest discover -s tests -t ." if package
                         else "python3 -m unittest discover -s tests")
            test_affected = test_full
            test_smoke = test_full + " -k smoke"
        elif has_tests:
            # pytest-style files. If pytest is not installed the run fails
            # loudly; it never falls through to a zero-test unittest pass.
            test_full = "python3 -m pytest -q"
            test_affected = "python3 -m pytest -q -m 'not slow'"
            test_smoke = "python3 -m pytest -q -m smoke"
        else:
            test_full = test_affected = test_smoke = ""
        cmds = {
            "test_full": test_full,
            "test_affected": test_affected,
            "test_smoke": test_smoke,
            "lint": ("ruff check ." if shutil.which("ruff")
                     else "python3 -m compileall -q ."),
            "build": "python3 -m compileall -q workflow" if (root / "workflow").is_dir() else "",
        }
    elif (root / "package.json").exists():
        stack = "node"
        try:
            pkg = json.loads((root / "package.json").read_text(encoding="utf-8"))
            scripts = pkg.get("scripts", {})
        except json.JSONDecodeError:
            scripts = {}
        cmds = {
            "test_full": "npm test" if "test" in scripts else "",
            "test_affected": "npm test -- --changed" if "test" in scripts else "",
            "test_smoke": "npm test" if "test" in scripts else "",
            "lint": "npm run lint" if "lint" in scripts else "",
            "build": "npm run build" if "build" in scripts else "",
        }
    elif (root / "go.mod").exists():
        stack = "go"
        cmds = {"test_full": "go test ./...", "test_affected": "go test ./...",
                "test_smoke": "go test ./... -run Smoke", "lint": "go vet ./...",
                "build": "go build ./..."}
    elif (root / "Cargo.toml").exists():
        stack = "rust"
        cmds = {"test_full": "cargo test", "test_affected": "cargo test",
                "test_smoke": "cargo test smoke", "lint": "cargo clippy -- -D warnings",
                "build": "cargo build"}
    else:
        stack = "unknown"
        cmds = {k: "" for k in ("test_full", "test_affected", "test_smoke", "lint", "build")}

    if make_text:
        for role, target in (("test_full", "test"), ("lint", "lint"),
                             ("build", "build"), ("test_smoke", "smoke")):
            if target in targets:
                cmds[role] = f"make {target}"
        if "test-affected" in targets:
            cmds["test_affected"] = "make test-affected"

    cmds.update({
        "integrity": "bash workflow/scripts/check-test-integrity.sh --verify",
        "callers": "python3 workflow/scripts/check-caller-existence.py --base main",
        "stats": "bash workflow/scripts/wp-stats.sh --base main",
    })
    return {"stack": stack, "commands": cmds}


def fresh_config(detected: dict, merge_mode: str, review_mode: str) -> dict:
    return {
        "version": 2,
        "stack": [detected["stack"]],
        "commands": detected["commands"],
        "integrity": {"test_paths": [], "count_cmd": ""},
        "mode": {"merge": merge_mode, "review": review_mode, "questions_max": 12},
        "review": {"approvers": [], "status_context": "risk-gate"},
        "risk_triggers": {},
    }


def merge_config(existing: dict, detected: dict, merge_mode: str, review_mode: str,
                 override_review: bool = False) -> tuple[dict, list[str]]:
    """Preserve project edits; fill only roles that are missing or unset.

    `mode.merge` and an existing `mode.review` are project configuration and are
    kept. A missing `mode.review` is filled with the solo default. An explicit
    --review-mode on --upgrade is the migration path for an existing strict
    installation and overrides the stored value; passing the flag by accident
    cannot happen because the CLI default is None.
    """
    merged = json.loads(json.dumps(existing))
    merged.setdefault("version", 2)

    stack = merged.get("stack")
    if (not isinstance(stack, list) or not stack or stack == ["unknown"]) \
            and detected["stack"] != "unknown":
        merged["stack"] = [detected["stack"]]

    commands = merged.get("commands")
    if not isinstance(commands, dict):
        commands = {}
    filled: list[str] = []
    for role, value in detected["commands"].items():
        current = commands.get(role)
        if not isinstance(current, str) or not current.strip():
            if value:
                commands[role] = value
                filled.append(role)
            else:
                commands.setdefault(role, "")
    merged["commands"] = commands

    merged.setdefault("integrity", {"test_paths": [], "count_cmd": ""})

    mode = merged.get("mode")
    if not isinstance(mode, dict):
        mode = {}
    mode.setdefault("merge", merge_mode)
    mode.setdefault("review", review_mode)
    if override_review:
        mode["review"] = review_mode
    mode.setdefault("questions_max", 12)
    merged["mode"] = mode

    review = merged.get("review")
    if not isinstance(review, dict):
        review = {}
    review.setdefault("approvers", [])
    review.setdefault("status_context", "risk-gate")
    merged["review"] = review

    merged.setdefault("risk_triggers", {})
    return merged, filled


def read_constitution(source: Path) -> str:
    path = source / "AGENTS.md"
    if not path.exists():
        return ""
    return path.read_text(encoding="utf-8").strip() + "\n"


def constitution_block(text: str) -> str:
    return f"{AGENTS_BEGIN}\n{CONSTITUTION_MARK}\n{text.strip()}\n{AGENTS_END}"


def merge_block(path: Path, begin: str, end: str, block: str, *,
                create_with: str | None = None, create_block: str | None = None,
                dry: bool = False) -> str:
    if not path.exists():
        if create_block is not None:
            new = create_block.rstrip() + "\n"
        elif create_with is not None:
            new = create_with.rstrip() + "\n\n" + block + "\n"
        else:
            return "absent"
        if not dry:
            path.write_text(new, encoding="utf-8")
        return "created"
    text = path.read_text(encoding="utf-8")
    if begin in text and end in text:
        head, rest = text.split(begin, 1)
        _, tail = rest.split(end, 1)
        new = head + block + tail
        if new != text:
            if not dry:
                path.write_text(new, encoding="utf-8")
            return "updated"
        return "unchanged"
    if not dry:
        path.write_text(text.rstrip() + "\n\n" + block + "\n", encoding="utf-8")
    return "appended"


def copy_workflow(source: Path, target: Path, dry: bool) -> list[str]:
    src = source / "workflow"
    dst = target / "workflow"
    changed: list[str] = []
    for item in sorted(src.rglob("*")):
        rel = item.relative_to(src)
        if any(part == "__pycache__" for part in rel.parts):
            continue
        if rel.parts and rel.parts[0] in {"tests", "state"}:
            continue
        if rel.as_posix() in {"config.json", "process/CALIBRATION.csv", "CONSTITUTION.md"}:
            continue
        if item.is_dir():
            continue
        dest = dst / rel
        if dest.exists() and dest.read_bytes() == item.read_bytes():
            continue
        changed.append(str(dest))
        if not dry:
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(item, dest)
    return changed


def write_if_absent(path: Path, content: str, dry: bool) -> str:
    if path.exists():
        return "kept"
    if not dry:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return "created"


def write_ci(path: Path, content: str, dry: bool) -> str:
    """Write the generated workflow, but never overwrite a hand-edited one."""
    if not path.exists():
        if not dry:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        return "created"
    text = path.read_text(encoding="utf-8")
    if not text.startswith(GENERATED_CI_HEADER):
        return "kept (hand-edited)"
    if text == content:
        return "unchanged"
    if not dry:
        path.write_text(content, encoding="utf-8")
    return "updated"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--target", default=".")
    ap.add_argument("--source", default=None)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--upgrade", action="store_true")
    ap.add_argument("--merge-mode", choices=("human", "auto"), default=None,
                    help="mode.merge for a newly created config.json "
                         "(default: human; auto is an explicit opt-in)")
    ap.add_argument("--review-mode", choices=("advisory", "risk-triggered", "human"),
                    default=None,
                    help="mode.review for a new config (default: advisory). With "
                         "--upgrade an explicit value migrates an existing config; "
                         "omitting it preserves the project's mode")
    ap.add_argument("--reset-config", action="store_true",
                    help="regenerate workflow/config.json, discarding project edits")
    ap.add_argument("--no-readme", action="store_true")
    ap.add_argument("--commit", action="store_true")
    args = ap.parse_args(argv)
    merge_mode = args.merge_mode or "human"
    review_mode = args.review_mode or "advisory"

    source = Path(args.source).resolve() if args.source else Path(__file__).resolve().parents[2]
    target = Path(args.target).resolve()
    if not (source / "workflow" / "START.md").exists():
        print(f"error: source {source} is not a workflow kit")
        return 2
    target.mkdir(parents=True, exist_ok=True)
    same = source == target

    state_path = target / "workflow" / "state" / "install.json"
    if state_path.exists() and not args.upgrade and not same:
        try:
            installed = json.loads(state_path.read_text(encoding="utf-8")).get("version")
        except json.JSONDecodeError:
            installed = None
        if installed == VERSION:
            print(f"already installed at {VERSION} — nothing to do")
            return 0
        print(f"installed version {installed}; re-run with --upgrade")
        return 3

    plan: dict[str, Any] = {"version": VERSION, "target": str(target), "kit": same,
                            "stack": None, "files": [], "blocks": {},
                            "mode": {"merge": merge_mode, "review": review_mode}}

    if same:
        print("kit repository: no copy, no CI generation")
    else:
        changed = copy_workflow(source, target, args.dry_run)
        plan["files"] = changed
        print(f"workflow files: {len(changed)} to write")

        constitution = read_constitution(source)
        if constitution:
            dest = target / "workflow" / "CONSTITUTION.md"
            if dest.exists() and dest.read_text(encoding="utf-8") == constitution:
                status = "unchanged"
            else:
                status = "created" if not dest.exists() else "updated"
                if not args.dry_run:
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    dest.write_text(constitution, encoding="utf-8")
            plan["blocks"]["workflow/CONSTITUTION.md"] = status
            print(f"constitution: {status} — workflow/CONSTITUTION.md")

        agents = target / "AGENTS.md"
        block = AGENTS_BLOCK
        if agents.exists() and CONSTITUTION_MARK in agents.read_text(encoding="utf-8"):
            # A previous install wrote the constitution itself into AGENTS.md.
            block = constitution_block(constitution) if constitution else AGENTS_BLOCK
        plan["blocks"]["AGENTS.md"] = merge_block(
            agents, AGENTS_BEGIN, AGENTS_END, block,
            create_block=constitution_block(constitution) if constitution else None,
            dry=args.dry_run,
        )

        readme = target / "README.md"
        if not args.no_readme:
            plan["blocks"]["README.md"] = merge_block(
                readme, README_BEGIN, README_END, README_BLOCK, dry=args.dry_run,
            )

    cfg_path = target / "workflow" / "config.json"
    detected = detect(target)
    plan["stack"] = detected["stack"]
    if not cfg_path.exists() or args.reset_config:
        config = fresh_config(detected, merge_mode, review_mode)
        status = "created" if not cfg_path.exists() else "reset"
        if not args.dry_run:
            cfg_path.parent.mkdir(parents=True, exist_ok=True)
            cfg_path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
        print(f"config: {status} ({detected['stack']} detected, "
              f"merge: {merge_mode}, review: {review_mode})")
    elif args.upgrade:
        try:
            existing = json.loads(cfg_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            status = f"invalid JSON left untouched ({exc}); use --reset-config"
            print(f"config: {status}")
        else:
            merged, filled = merge_config(
                existing, detected, merge_mode, review_mode,
                override_review=args.review_mode is not None,
            )
            status = "merged" if merged != existing else "kept"
            if merged != existing and not args.dry_run:
                cfg_path.write_text(json.dumps(merged, indent=2) + "\n", encoding="utf-8")
            detail = f" (filled: {', '.join(filled)})" if filled else ""
            print(f"config: {status}{detail}")
            active_review = (merged.get("mode") or {}).get("review", review_mode)
            print(f"review mode: {active_review}")
            if args.review_mode is None and active_review != "advisory":
                print(f"note: review mode is '{active_review}' (opt-in). The solo default is "
                      "'advisory'; run install.py --upgrade --review-mode advisory to migrate.")
    else:
        status = "kept"
        print("config: kept")
    plan["blocks"]["config"] = status

    if not args.dry_run:
        for script in list((target / "workflow" / "scripts").glob("*.py")) + \
                      list((target / "workflow" / "scripts").glob("*.sh")):
            script.chmod(0o755)

    if not same:
        for name, template in (("DECISIONS.md", "DECISIONS.seed.md"),
                               ("CHANGELOG.md", "CHANGELOG.seed.md")):
            dest = target / name
            src = source / "workflow" / "templates" / template
            status = write_if_absent(dest, src.read_text(encoding="utf-8") if src.exists() else "",
                                     args.dry_run)
            plan["blocks"][name] = status

        ci = target / ".github" / "workflows" / "wp.yml"
        plan["blocks"]["ci"] = write_ci(
            ci, CI_TEMPLATE.format(version=VERSION), args.dry_run
        )

    baseline = target / "workflow" / "state" / "test-baseline.json"
    if not same and not baseline.exists() and \
            (target / "workflow" / "scripts" / "check-test-integrity.sh").exists():
        snap = None
        if not args.dry_run:
            snap = subprocess.run(
                ["bash", "workflow/scripts/check-test-integrity.sh", "--snapshot",
                 "--baseline", "workflow/state/test-baseline.json"],
                cwd=target, capture_output=True, text=True,
            )
        if baseline.exists():
            print("baseline: snapshotted")
        elif snap is not None and snap.returncode != 0:
            reason = (snap.stderr or snap.stdout).strip().splitlines()
            print(f"baseline: skipped — {reason[-1] if reason else 'snapshot failed'}")
        else:
            print("baseline: skipped — no tests detected")

    if not args.dry_run:
        unchanged = False
        if same and state_path.exists():
            try:
                current = json.loads(state_path.read_text(encoding="utf-8"))
                unchanged = (current.get("version") == VERSION
                             and current.get("kit") is True)
            except json.JSONDecodeError:
                unchanged = False
        if not unchanged:
            state_path.parent.mkdir(parents=True, exist_ok=True)
            plan["installed_at"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
            state_path.write_text(json.dumps(plan, indent=2) + "\n", encoding="utf-8")

    if args.commit and not args.dry_run:
        subprocess.run(["git", "add", "-A"], cwd=target, check=False)
        subprocess.run(
            ["git", "commit", "-m", f"chore: install workflow kit v{VERSION}"],
            cwd=target, check=False,
        )

    print(json.dumps({"version": VERSION, "target": str(target),
                      "files": len(plan["files"]), "blocks": plan["blocks"]}, indent=2))
    if args.dry_run:
        print("dry-run: nothing written")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
