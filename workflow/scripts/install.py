#!/usr/bin/env python3
"""Install or upgrade the workflow kit in a repository.

Usage:
    python3 workflow/scripts/install.py --target . [--dry-run] [--upgrade]
                                       [--merge-mode human|auto]
                                       [--review-mode advisory|risk-triggered|human]
                                       [--reset-config] [--no-readme] [--commit]

Guarantees:
  * never overwrites README.md, AGENTS.md, DECISIONS.md or CHANGELOG.md;
  * idempotent: a second run changes nothing;
  * writes one method directory (`workflow/`), one CI file, and marker blocks;
  * installs the full constitution as `workflow/CONSTITUTION.md` and, when the
    target has no AGENTS.md, uses it as that file's content;
  * on --upgrade, preserves project edits in workflow/config.json and only
    fills command roles that are missing or unset; an explicitly passed
    --review-mode migrates the review policy, and a missing mode.review is
    filled with the solo default;
  * detects the stack and writes workflow/config.json;
  * records what it did in workflow/state/install.json.

Defaults are the solo-developer policy: `mode.merge: human` (the owner reviews
and merges) and `mode.review: advisory` (risk findings are reported but do not
block). Independent review and automatic merging are explicit opt-ins.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

VERSION = "2.2.0"
AGENTS_BEGIN = "<!-- workflow:begin -->"
AGENTS_END = "<!-- workflow:end -->"
CONSTITUTION_MARK = "<!-- workflow:constitution -->"
README_BEGIN = "<!-- workflow-kit:begin -->"
README_END = "<!-- workflow-kit:end -->"
GENERATED_CI_HEADER = "# Generated by workflow-kit"

AGENTS_BLOCK = """<!-- workflow:begin -->
## Agent workflow (workflow-kit)

The full constitution is `workflow/CONSTITUTION.md`; it is normative in full.
Its rules, condensed:

- **Delivery unit.** One full work package per branch and PR. Do not split a
  package to fit a turn, a context window or a session. An incomplete package is
  a reported blocker, not a delivery.
- **Completion.** Define completion (WP, acceptance checklist, prerequisites,
  branch) before coding, then map delivered behaviour to it. Name blockers
  instead of rounding up.
- **Evidence.** Untested implementation does not satisfy a package. Evidence is
  command output, not assertion. Never edit, delete, weaken, rename or skip a
  test without recording and justifying it in the delivery declaration.
- **Reporting.** Lead with completed criteria and remaining blockers; report
  implementation, tests, docs and generated files separately, from diff
  statistics rather than from memory.
- **State.** Read the index at the top of `DECISIONS.md` before proposing an
  approach; `adopted` binds, `rejected` is not re-proposed unless its
  **Revisit if** is now true. Keep `progress.md` and `state.json` per
  `workflow/STATE.md`.
- **Review.** Machine gates first, a fresh-context verifier second, risk
  reporting third. The default is solo operation: `mode.merge: human` and
  `mode.review: advisory` — CI reports risk findings, the owner reviews and
  merges, and that merge accepts the reported risks. `mode.review:
  risk-triggered` or `human` requires an independent approval of the exact head
  commit; `mode.merge: auto` lets the agent merge only after every required
  check and the `risk-gate` status are green. A blocked gate is not mergeable.
- **Prohibited.** Weakening a test to get green, unrequested dependencies,
  invented services the spec does not define, marking a WP complete with an
  unverified criterion, starting the next package.

Routing: install and phases `workflow/START.md`; process
`workflow/WORKFLOW.md`; mechanisms `workflow/VERIFICATION.md`; review
`workflow/REVIEW.md`; commands and modes `workflow/config.json`.
<!-- workflow:end -->"""

