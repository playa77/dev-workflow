#!/usr/bin/env python3
"""Install or upgrade the workflow kit in a repository.

Usage:
    python3 workflow/scripts/install.py --target . [--dry-run] [--upgrade]
                                       [--no-readme] [--commit]

Guarantees:
  * never overwrites README.md, AGENTS.md, DECISIONS.md or CHANGELOG.md;
  * idempotent: a second run changes nothing;
  * writes one method directory (`workflow/`), one CI file, and marker blocks;
  * detects the stack and writes workflow/config.json;
  * records what it did in workflow/state/install.json.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

VERSION = "2.0.0"
AGENTS_BEGIN = "<!-- workflow:begin -->"
AGENTS_END = "<!-- workflow:end -->"
README_BEGIN = "<!-- workflow-kit:begin -->"
README_END = "<!-- workflow-kit:end -->"

AGENTS_BLOCK = """<!-- workflow:begin -->
## Agent workflow (workflow-kit v2)

- Read `workflow/START.md` first: install, bootstrap and phase routing.
- One full work package per branch and PR. An incomplete package is a reported
  blocker, not a delivery.
- Evidence is command output, not assertion. Never weaken a test to get green.
- Before proposing an approach, read the index at the top of `DECISIONS.md`.
  `adopted` binds; `rejected` means do not re-propose it unless its **Revisit if**
  is now true.
- Every user-visible change gets a line in `CHANGELOG.md` citing `(D-nnn, WP-nnn)`.
- Merge automatically when every gate is green, unless `risk-scan.py` reports a
  trigger; a trigger requires human review.
- Full rules: `workflow/WORKFLOW.md`; verification: `workflow/VERIFICATION.md`;
  review: `workflow/REVIEW.md`.
<!-- workflow:end -->"""

README_BLOCK = """<!-- workflow-kit:begin -->
## Development workflow

This repository uses the workflow kit. Agents start at `workflow/START.md`;
decisions are in `DECISIONS.md`, user-visible changes in `CHANGELOG.md`.
<!-- workflow-kit:end -->"""

CI_TEMPLATE = """# Generated by workflow-kit v{version}. Edit workflow/config.json, not this file
# by hand; `install.py --upgrade` regenerates the lanes from it.
name: wp

on:
  pull_request:
  push:
    branches: [main]

jobs:
  gates:
    name: workflow gates
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - uses: actions/setup-python@v5
        with:
          python-version: "3.12"
      - name: Config
        run: python3 workflow/scripts/check-config.py
      - name: Ledger
        run: python3 workflow/scripts/check-ledger.py --check
      - name: Changelog
        run: python3 workflow/scripts/check-changelog.py
      - name: Intake
        if: hashFiles('workflow/state/intake.json') != ''
        run: python3 workflow/scripts/check-intake.py
      - name: Work packages
        if: hashFiles('docs/wp/*.md') != ''
        run: python3 workflow/scripts/check-wp.py
      - name: Specification
        if: hashFiles('docs/spec/SPEC.md') != ''
        run: python3 workflow/scripts/check-spec.py
      - name: Roadmap
        if: hashFiles('docs/roadmap/ROADMAP.md') != ''
        run: python3 workflow/scripts/check-roadmap.py
      - name: Test integrity
        run: bash workflow/scripts/check-test-integrity.sh --verify
      - name: Caller existence
        env:
          BASE_REF: ${{{{ github.base_ref || 'main' }}}}
        run: python3 workflow/scripts/check-caller-existence.py --base "origin/$BASE_REF" --committed
      - name: Risk scan
        if: github.event_name == 'pull_request'
        env:
          BASE_REF: ${{{{ github.base_ref || 'main' }}}}
        run: python3 workflow/scripts/risk-scan.py --base "origin/$BASE_REF"
      - name: Full suite
        run: {test_full}
      - name: Declaration
        if: github.event_name == 'pull_request'
        env:
          PR_BODY: ${{{{ github.event.pull_request.body }}}}
        run: |
          printf '%s' "$PR_BODY" > /tmp/declaration.md
          python3 workflow/scripts/check-declaration.py /tmp/declaration.md
"""


def detect(root: Path) -> dict:
    def exists(*names: str) -> bool:
        return any((root / n).exists() for n in names)

    make = root / "Makefile"
    make_text = make.read_text(encoding="utf-8", errors="ignore") if make.exists() else ""
    targets = set(re.findall(r"^([A-Za-z0-9_.-]+):", make_text, re.M))

    if exists("pyproject.toml", "setup.py", "setup.cfg", "pytest.ini", "tox.ini"):
        stack = "python"
        has_pytest = subprocess.run(
            [sys.executable, "-c", "import pytest"], capture_output=True
        ).returncode == 0
        has_tests = (root / "tests").is_dir()
        if has_pytest:
            test_full = "python3 -m pytest -q"
            test_affected = "python3 -m pytest -q -m 'not slow'"
            test_smoke = "python3 -m pytest -q -m smoke"
        elif has_tests:
            test_full = "python3 -m unittest discover -s tests -t ."
            test_affected = test_full
            test_smoke = test_full + " -k smoke"
        else:
            test_full = test_affected = test_smoke = ""
        cmds = {
            "test_full": test_full,
            "test_affected": test_affected,
            "test_smoke": test_smoke,
            "lint": ("ruff check ." if shutil.which("ruff")
                     else "python3 -m compileall -q ."),
            "build": "python3 -m compileall -q workflow" if (root / "workflow").is_dir() else "",
        }
    elif (root / "package.json").exists():
        stack = "node"
        try:
            pkg = json.loads((root / "package.json").read_text(encoding="utf-8"))
            scripts = pkg.get("scripts", {})
        except json.JSONDecodeError:
            scripts = {}
        cmds = {
            "test_full": "npm test" if "test" in scripts else "",
            "test_affected": "npm test -- --changed" if "test" in scripts else "",
            "test_smoke": "npm test" if "test" in scripts else "",
            "lint": "npm run lint" if "lint" in scripts else "",
            "build": "npm run build" if "build" in scripts else "",
        }
    elif (root / "go.mod").exists():
        stack = "go"
        cmds = {"test_full": "go test ./...", "test_affected": "go test ./...",
                "test_smoke": "go test ./... -run Smoke", "lint": "go vet ./...",
                "build": "go build ./..."}
    elif (root / "Cargo.toml").exists():
        stack = "rust"
        cmds = {"test_full": "cargo test", "test_affected": "cargo test",
                "test_smoke": "cargo test smoke", "lint": "cargo clippy -- -D warnings",
                "build": "cargo build"}
    else:
        stack = "unknown"
        cmds = {k: "" for k in ("test_full", "test_affected", "test_smoke", "lint", "build")}

    if make_text:
        for role, target in (("test_full", "test"), ("lint", "lint"),
                             ("build", "build"), ("test_smoke", "smoke")):
            if target in targets:
                cmds[role] = f"make {target}"
        if "test-affected" in targets:
            cmds["test_affected"] = "make test-affected"

    cmds.update({
        "integrity": "bash workflow/scripts/check-test-integrity.sh --verify",
        "callers": "python3 workflow/scripts/check-caller-existence.py --base main",
        "stats": "bash workflow/scripts/wp-stats.sh --base main",
    })
    return {"stack": stack, "commands": cmds}


def merge_block(path: Path, begin: str, end: str, block: str, create_with: str | None) -> str:
    if not path.exists():
        if create_with is None:
            return "absent"
        path.write_text(create_with.rstrip() + "\n\n" + block + "\n", encoding="utf-8")
        return "created"
    text = path.read_text(encoding="utf-8")
    if begin in text and end in text:
        head, rest = text.split(begin, 1)
        _, tail = rest.split(end, 1)
        new = head + block + tail
        if new != text:
            path.write_text(new, encoding="utf-8")
            return "updated"
        return "unchanged"
    path.write_text(text.rstrip() + "\n\n" + block + "\n", encoding="utf-8")
    return "appended"


def copy_workflow(source: Path, target: Path, dry: bool) -> list[str]:
    src = source / "workflow"
    dst = target / "workflow"
    changed: list[str] = []
    for item in sorted(src.rglob("*")):
        rel = item.relative_to(src)
        if any(part == "__pycache__" for part in rel.parts):
            continue
        if rel.parts and rel.parts[0] in {"tests", "state"}:
            continue
        if rel.as_posix() in {"config.json", "process/CALIBRATION.csv"}:
            continue
        if item.is_dir():
            continue
        dest = dst / rel
        if dest.exists() and dest.read_bytes() == item.read_bytes():
            continue
        changed.append(str(dest))
        if not dry:
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(item, dest)
    return changed


def write_if_absent(path: Path, content: str, dry: bool) -> str:
    if path.exists():
        return "kept"
    if not dry:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return "created"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--target", default=".")
    ap.add_argument("--source", default=None)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--upgrade", action="store_true")
    ap.add_argument("--no-readme", action="store_true")
    ap.add_argument("--commit", action="store_true")
    args = ap.parse_args(argv)

    source = Path(args.source).resolve() if args.source else Path(__file__).resolve().parents[2]
    target = Path(args.target).resolve()
    if not (source / "workflow" / "START.md").exists():
        print(f"error: source {source} is not a workflow kit")
        return 2
    target.mkdir(parents=True, exist_ok=True)
    same = source == target

    state_path = target / "workflow" / "state" / "install.json"
    if state_path.exists() and not args.upgrade and not same:
        try:
            installed = json.loads(state_path.read_text(encoding="utf-8")).get("version")
        except json.JSONDecodeError:
            installed = None
        if installed == VERSION:
            print(f"already installed at {VERSION} — nothing to do")
            return 0
        print(f"installed version {installed}; re-run with --upgrade")
        return 3

    plan: dict[str, Any] = {"version": VERSION, "target": str(target), "stack": None,
                            "files": [], "blocks": {}}

    if not same:
        changed = copy_workflow(source, target, args.dry_run)
        plan["files"] = changed
        print(f"workflow files: {len(changed)} to write")

    if not same:
        agents = target / "AGENTS.md"
        plan["blocks"]["AGENTS.md"] = merge_block(
            agents, AGENTS_BEGIN, AGENTS_END, AGENTS_BLOCK,
            create_with="# AGENTS.md\n\nOperating rules for agents in this repository.",
        ) if not args.dry_run else ("would merge" if agents.exists() else "would create")

        readme = target / "README.md"
        if not args.no_readme:
            plan["blocks"]["README.md"] = merge_block(
                readme, README_BEGIN, README_END, README_BLOCK, create_with=None,
            ) if not args.dry_run else "would append"

    cfg_path = target / "workflow" / "config.json"
    if not cfg_path.exists() or args.upgrade:
        detected = detect(target)
        plan["stack"] = detected["stack"]
        config = {
            "version": 2,
            "stack": [detected["stack"]],
            "commands": detected["commands"],
            "integrity": {"test_paths": [], "count_cmd": ""},
            "mode": {"merge": "auto", "review": "risk-triggered", "questions_max": 12},
            "risk_triggers": {},
        }
        if not args.dry_run:
            cfg_path.parent.mkdir(parents=True, exist_ok=True)
            cfg_path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
        print(f"config: {detected['stack']} detected")
    else:
        plan["stack"] = json.loads(cfg_path.read_text(encoding="utf-8")).get("stack", ["?"])
        print("config: kept")

    if not args.dry_run:
        for script in list((target / "workflow" / "scripts").glob("*.py")) + \
                      list((target / "workflow" / "scripts").glob("*.sh")):
            script.chmod(0o755)

    if not same:
        for name, template in (("DECISIONS.md", "DECISIONS.seed.md"), ("CHANGELOG.md", "CHANGELOG.seed.md")):
            dest = target / name
            src = source / "workflow" / "templates" / template
            status = write_if_absent(dest, src.read_text(encoding="utf-8") if src.exists() else "", args.dry_run)
            plan["blocks"][name] = status

    ci = target / ".github" / "workflows" / "wp.yml"
    test_cmd = "true"
    if cfg_path.exists():
        try:
            test_cmd = (json.loads(cfg_path.read_text(encoding="utf-8"))
                        .get("commands", {}).get("test_full") or "true")
        except json.JSONDecodeError:
            test_cmd = "true"
    if not ci.exists():
        if not args.dry_run:
            ci.parent.mkdir(parents=True, exist_ok=True)
            ci.write_text(CI_TEMPLATE.format(version=VERSION, test_full=test_cmd), encoding="utf-8")
        plan["blocks"]["ci"] = "created"
    else:
        alt = target / ".github" / "workflows" / "wp-workflow.yml"
        if not alt.exists():
            if not args.dry_run:
                alt.write_text(CI_TEMPLATE.format(version=VERSION, test_full=test_cmd), encoding="utf-8")
            plan["blocks"]["ci"] = "existing kept; wrote wp-workflow.yml"
        else:
            plan["blocks"]["ci"] = "existing kept"

    baseline = target / "workflow" / "state" / "test-baseline.json"
    if not baseline.exists() and (target / "workflow" / "scripts" / "check-test-integrity.sh").exists():
        snap = None
        if not args.dry_run:
            snap = subprocess.run(
                ["bash", "workflow/scripts/check-test-integrity.sh", "--snapshot",
                 "--baseline", "workflow/state/test-baseline.json"],
                cwd=target, capture_output=True, text=True,
            )
        if baseline.exists():
            print("baseline: snapshotted")
        elif snap is not None and snap.returncode != 0:
            reason = (snap.stderr or snap.stdout).strip().splitlines()
            print(f"baseline: skipped — {reason[-1] if reason else 'snapshot failed'}")
        else:
            print("baseline: skipped — no tests detected")

    if not args.dry_run:
        state_path.parent.mkdir(parents=True, exist_ok=True)
        plan["installed_at"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
        state_path.write_text(json.dumps(plan, indent=2) + "\n", encoding="utf-8")

    if args.commit and not args.dry_run:
        subprocess.run(["git", "add", "-A"], cwd=target, check=False)
        subprocess.run(
            ["git", "commit", "-m", f"chore: install workflow kit v{VERSION}"],
            cwd=target, check=False,
        )

    print(json.dumps({"version": VERSION, "target": str(target),
                      "files": len(plan["files"]), "blocks": plan["blocks"]}, indent=2))
    if args.dry_run:
        print("dry-run: nothing written")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
